//! Lovejoin's generalized scripts before their parameters, the ones every
//! token pool runs: the data layer's own copy of what
//! `seedelf-core/src/lovejoin/templates.rs` pins (Aiken v1.1.24, Lovejoin
//! 8131b1d). This crate can't depend on seedelf-core (the owner,
//! 2026-10-17: core keeps its own copy), so the two are held to one file of
//! vectors that core writes from its own derive,
//! `seedelf-core/tests/fixtures/lovejoin-pool-vectors.json`.
//!
//! A launch spends a seed UTxO, and the seed fixes everything else:
//! `one_shot_mint(seed_tx_id, seed_idx, holder)` hashes to P, the pool's id;
//! `mix_logic(P, "lovejoin")` to L; `mix_box(L)` to M, where the boxes sit;
//! `fee_contract(P, "lovejoin")` to F.

use cryptoxide::blake2b::Blake2b;

use super::flat::{self, Malformed, cbor_head};
use crate::constants::bytes;

/// `reference_holder`'s hash. It takes no parameters and is always false:
/// every launch's reference UTxO sits at it for good.
pub const HOLDER_HASH: &str = "288fea77a0f674c6080aadd8ed3ca42cd5a920bf1f00c0d3e63306e4";

/// The NFT's name, `one_shot_mint` allows no other: ASCII `lovejoin`.
pub const NFT_NAME: &[u8] = b"lovejoin";

/// A launch's scripts' hashes, all fixed by its seed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Derived {
    /// P: the NFT's policy, the pool's id.
    pub policy: [u8; 28],
    /// L: its credential takes every mix's zero withdrawal; a standard launch registers it.
    pub mix_logic: [u8; 28],
    /// M: where the boxes sit.
    pub mix_box: [u8; 28],
    /// F: the fee shards'. The wallet never uses them, but the datum names F.
    pub fee_contract: [u8; 28],
}

/// A Plutus V3 script's hash: `blake2b_224(0x03 ‖ script)`.
pub fn script_hash(script: &[u8]) -> [u8; 28] {
    let mut preimage = Vec::with_capacity(script.len() + 1);
    preimage.push(0x03);
    preimage.extend_from_slice(script);
    let mut hash = [0u8; 28];
    Blake2b::blake2b(&mut hash, &preimage, &[]);
    hash
}

/// A `Data` byte string's CBOR, at most 64 bytes (every parameter here is).
fn data_bytes(b: &[u8]) -> Vec<u8> {
    [cbor_head(2, b.len() as u64), b.to_vec()].concat()
}

fn hash_of(template: &str, params: &[Vec<u8>]) -> Result<[u8; 28], Malformed> {
    Ok(script_hash(&flat::apply(&bytes(template), params)?))
}

/// P: the policy of the NFT a launch spending `seed_tx#seed_index` mints.
/// One application, cheaper than [`derive`]'s four: what finds a seed.
pub fn policy_of(seed_tx: &[u8; 32], seed_index: u64) -> Result<[u8; 28], Malformed> {
    hash_of(
        ONE_SHOT_MINT,
        &[
            data_bytes(seed_tx),
            cbor_head(0, seed_index),
            data_bytes(&bytes(HOLDER_HASH)),
        ],
    )
}

/// Every script a launch spending `seed_tx#seed_index` runs.
pub fn derive(seed_tx: &[u8; 32], seed_index: u64) -> Result<Derived, Malformed> {
    let policy = policy_of(seed_tx, seed_index)?;
    let named = [data_bytes(&policy), data_bytes(NFT_NAME)];
    let mix_logic = hash_of(MIX_LOGIC, &named)?;
    Ok(Derived {
        policy,
        mix_logic,
        mix_box: hash_of(MIX_BOX, &[data_bytes(&mix_logic)])?,
        fee_contract: hash_of(FEE_CONTRACT, &named)?,
    })
}

/// The four templates, unapplied, as a transaction would carry them.
#[cfg(test)]
pub fn all() -> Vec<Vec<u8>> {
    [ONE_SHOT_MINT, MIX_LOGIC, MIX_BOX, FEE_CONTRACT]
        .map(bytes)
        .to_vec()
}

