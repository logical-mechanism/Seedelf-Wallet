use pallas_primitives::conway::{BigInt, PlutusData};
use uplc::ast::{DeBruijn, Program};

/// The Lovejoin commit [`Set::V1`]'s scripts were built at.
pub const COMMIT: &str = "8131b1dffd988932fce187acfb35e740d61d460f";

/// The Lovejoin commit [`Set::V2`]'s scripts were built at.
pub const COMMIT_V2: &str = "29573c58ccee47f2dfde4e06e7133435369b55f9";

/// One of Lovejoin's versions of the generalized scripts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Set {
    /// 8131b1d's, the first: retired.
    V1,
    /// 29573c5's: 8131b1d's with xor32 checking both lengths.
    V2,
}

impl Set {
    /// The Lovejoin commit the set was built at.
    pub fn commit(self) -> &'static str {
        match self {
            Set::V1 => COMMIT,
            Set::V2 => COMMIT_V2,
        }
    }

    /// The set's `mix_logic`, the one template that differs.
    fn mix_logic(self) -> &'static str {
        match self {
            Set::V1 => MIX_LOGIC,
            Set::V2 => MIX_LOGIC_V2,
        }
    }
}

/// `reference_holder`'s hash: every launch's reference UTxO, and the
/// reference scripts the wallet's launches publish, sit at it for good.
pub const REFERENCE_HOLDER_HASH: [u8; 28] =
    hex!("288fea77a0f674c6080aadd8ed3ca42cd5a920bf1f00c0d3e63306e4");

/// The NFT's name, `one_shot_mint` allows no other: ASCII `lovejoin`.
pub const NFT_NAME: &[u8] = b"lovejoin";

/// A Plutus V3 script: its bytes as a witness or a reference output carries
/// them (the flat program in a CBOR byte string), and its hash.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Script {
    pub hash: [u8; 28],
    pub cbor: Vec<u8>,
}

impl Script {
    fn new(cbor: Vec<u8>) -> Self {
        Script {
            hash: script_hash(&cbor),
            cbor,
        }
    }
}

/// A launch's scripts, all fixed by its seed and its set.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Derived {
    /// The set they come from.
    pub set: Set,
    /// P: the pool's id.
    pub one_shot_mint: Script,
    /// L: its credential takes the zero withdrawal every mix and withdraw make.
    pub mix_logic: Script,
    /// M: where the boxes sit.
    pub mix_box: Script,
    /// F: the fee shards' address, which the wallet never uses.
    pub fee_contract: Script,
}

impl Derived {
    /// P, the policy of the pool's NFT.
    pub fn policy(&self) -> [u8; 28] {
        self.one_shot_mint.hash
    }
}

/// A Plutus V3 script's hash: `blake2b_224(0x03 ‖ script)`.
pub fn script_hash(cbor: &[u8]) -> [u8; 28] {
    let mut preimage = Vec::with_capacity(cbor.len() + 1);
    preimage.push(0x03);
    preimage.extend_from_slice(cbor);
    *Hasher::<224>::hash(&preimage)
}

fn bytes(b: &[u8]) -> PlutusData {
    PlutusData::BoundedBytes(b.to_vec().into())
}

/// `template` applied to `params`, in order, as `aiken blueprint apply` does
/// it: each one a `Data` constant, the program `Apply`'d to it.
fn apply(template: &str, params: Vec<PlutusData>) -> Result<Script> {
    let cbor = hex::decode(template).context("A bundled Lovejoin template isn't hex")?;
    let mut flat = Vec::new();
    let mut program = Program::<DeBruijn>::from_cbor(&cbor, &mut flat)
        .map_err(|e| anyhow!("A bundled Lovejoin template can't be read: {e}"))?;
    for param in params {
        program = program.apply_data(param);
    }
    let applied = program
        .to_cbor()
        .map_err(|e| anyhow!("A Lovejoin script can't be encoded: {e}"))?;
    Ok(Script::new(applied))
}

/// `one_shot_mint` for the seed `seed_tx#seed_index`: its hash is the
/// policy of the NFT a launch spending that seed mints, the pool's id.
pub fn one_shot_mint(seed_tx: &[u8; 32], seed_index: u64) -> Result<Script> {
    let index = i64::try_from(seed_index).context("A seed's output index is out of range")?;
    apply(
        ONE_SHOT_MINT,
        vec![
            bytes(seed_tx),
            PlutusData::BigInt(BigInt::Int(Int::from(index))),
            bytes(&REFERENCE_HOLDER_HASH),
        ],
    )
}

/// The scripts a launch spending the seed `seed_tx#seed_index` runs on
/// [`Set::V1`], the set the pools before v2 run.
pub fn derive(seed_tx: &[u8; 32], seed_index: u64) -> Result<Derived> {
    derive_in(Set::V1, seed_tx, seed_index)
}

/// The scripts a launch spending the seed `seed_tx#seed_index` runs on `set`.
pub fn derive_in(set: Set, seed_tx: &[u8; 32], seed_index: u64) -> Result<Derived> {
    #[cfg(test)]
    super::counted::count(&super::counted::DERIVES);
    let one_shot_mint = one_shot_mint(seed_tx, seed_index)?;
    let mix_logic = mix_logic_of(set, &one_shot_mint.hash)?;
    finish(set, one_shot_mint, mix_logic)
}

/// The scripts a launch spending the seed `seed_tx#seed_index` runs, on the
/// set whose `mix_logic` hashes to `mix_logic`, the one a pool's datum
/// names. When no set's does, V2's: their L then isn't the datum's, which
/// [`super::verify_pool`] refuses, after the policy as before. P is applied
/// once, and V2's L is tried first.
pub fn derive_for(seed_tx: &[u8; 32], seed_index: u64, mix_logic: &[u8; 28]) -> Result<Derived> {
    #[cfg(test)]
    super::counted::count(&super::counted::DERIVES);
    let one_shot_mint = one_shot_mint(seed_tx, seed_index)?;
    let v2 = mix_logic_of(Set::V2, &one_shot_mint.hash)?;
    if &v2.hash != mix_logic {
        let v1 = mix_logic_of(Set::V1, &one_shot_mint.hash)?;
        if &v1.hash == mix_logic {
            return finish(Set::V1, one_shot_mint, v1);
        }
    }
    finish(Set::V2, one_shot_mint, v2)
}

/// L for the pool whose NFT policy is `policy`, on `set`.
fn mix_logic_of(set: Set, policy: &[u8; 28]) -> Result<Script> {
    apply(set.mix_logic(), vec![bytes(policy), bytes(NFT_NAME)])
}

/// The rest of a launch's scripts once P and L are applied: M and F.
fn finish(set: Set, one_shot_mint: Script, mix_logic: Script) -> Result<Derived> {
    let policy = one_shot_mint.hash;
    let mix_box = apply(MIX_BOX, vec![bytes(&mix_logic.hash)])?;
    let fee_contract = apply(FEE_CONTRACT, vec![bytes(&policy), bytes(NFT_NAME)])?;
    Ok(Derived {
        set,
        one_shot_mint,
        mix_logic,
        mix_box,
        fee_contract,
    })
}

/// [`Set::V1`]'s unapplied templates' own hashes, `one_shot_mint`,
/// `mix_logic`, `mix_box` and `fee_contract`: what pins the bundled bytes.
pub fn unapplied_hashes() -> [[u8; 28]; 4] {
    unapplied_hashes_in(Set::V1)
}

/// [`unapplied_hashes`] for `set`.
pub fn unapplied_hashes_in(set: Set) -> [[u8; 28]; 4] {
    [ONE_SHOT_MINT, set.mix_logic(), MIX_BOX, FEE_CONTRACT]
        .map(|t| script_hash(&hex::decode(t).expect("bundled hex")))
}

/// `reference_holder`, which takes no parameters.
pub fn reference_holder() -> Result<Script> {
    apply(REFERENCE_HOLDER, Vec::new())
}

