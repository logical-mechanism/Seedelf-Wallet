//! Lovejoin's generalized scripts, the ones its token pools run, before
//! their parameters: what proves a pool is genuine. Built with `aiken build`
//! (Aiken v1.1.24) at Lovejoin [`COMMIT`], the merge of its PR #163, whose
//! contracts are byte for byte those Lovejoin's own token pool on preprod
//! runs.
//!
//! A launch spends a seed UTxO; the seed fixes everything else:
//!
//! - `one_shot_mint(seed_tx_id, seed_idx, reference_holder_hash)` hashes to
//!   P, the policy of the pool's one `lovejoin` NFT;
//! - `mix_logic(P, "lovejoin")` to L;
//! - `mix_box(L)` to M, where the boxes sit;
//! - `fee_contract(P, "lovejoin")` to F.
//!
//! [`derive_in`] applies them. Each of Lovejoin's versions of these scripts
//! is a [`Set`] beside the others, never an edit to one: a pool launched on
//! a set runs it for good.
//!
//! - [`Set::V1`], at [`COMMIT`], is the first. Its pools are retired: they
//!   take no new boxes, and the wallet only brings boxes back from them.
//! - [`Set::V2`], at [`COMMIT_V2`] (Lovejoin's PRs #165 and #166), is V1
//!   with xor32 checking both its operands' lengths. Only `mix_logic`
//!   changes, so a seed makes the same P under either set, and only L, and
//!   M through it, tell them apart. The wallet launches V2 alone. Its bytes
//!   are the ones `seedelf-verification` proves.
//!
//! The classic pool, live since before PR #163, runs older scripts of its
//! own; it's bundled whole ([`super::Protocol::of`]) and never derived.

use anyhow::{Context, Result, anyhow};
