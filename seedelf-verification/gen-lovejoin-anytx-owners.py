#!/usr/bin/env python3
"""Generate bounded arbitrary-context Owner proofs for three and four boxes."""
from pathlib import Path

root = Path(__file__).resolve().parent
for n in (3, 4):
    points = ' '.join(f'a{i} b{i}' for i in range(1, n + 1))
    boxes = ' '.join(f'bx{i}' for i in range(2, n + 1))
    box_args = ' '.join(f'(bx{i} : BoxFields)' for i in range(2, n + 1))
    box_refs = ', '.join(['f.boxRef'] + [f'bx{i}.ref' for i in range(2, n + 1)] + ['f.keyRef'])
    ins = ['boxIn f.boxRef M f.boxStake f.boxValue f.boxScript a1 b1'] + [
        f'boxIn bx{i}.ref M bx{i}.stake bx{i}.value bx{i}.script a{i} b{i}' for i in range(2, n + 1)] + [
        'otherIn f.keyRef 0 key f.keyStake f.keyValue f.keyDatum f.keyScript']
    ins_data = ',\n      '.join(ins)
    all_proofs = ', '.join(f'proofData p.t{i} p.z{i}' for i in range(1, n + 1))
    missing_proofs = ', '.join(f'proofData p.t{i} p.z{i}' for i in range(1, n))
    pts = ''.join(f'    wellFormed a{i} b{i} = true →\n' for i in range(1, n + 1))
    proofs = ''.join(f'    ownProof M f.tx.outputs [{box_refs}] a{i} b{i} p.t{i} p.z{i} = true →\n' for i in range(1, n + 1))
    params = f'(P M {points} key : ByteString) (f : Fields) {box_args} (p : Proofs)'
    call = f'P M {points} key f {boxes} p'
    fuel = 10000 + 5000 * n
    src = f'''import Lovejoin.AnyTx.OwnerTwo
import Blaster

/-! Owner withdrawal of {n} boxes and a following key input. Outputs, input references,
input values and unused transaction fields are arbitrary. The sole carrier uses the
fixed reference value and datum shape in `OwnerOne`. Generated by
`gen-lovejoin-anytx-owners.py`. -/
namespace Lovejoin.AnyTx.Owner{n}
open CardanoLedgerApi.IsData.Class (toTerm)
open PlutusCore.ByteString (ByteString)
open PlutusCore.Data (Data)
open PlutusCore.UPLC.Term (Term)
open PlutusCore.UPLC.Utils
open Seedelf.V1 (returnsUnit)
open Lovejoin.Classic (wellFormed)
open Lovejoin.Template (nftName)
open Lovejoin.AnyTx
open Lovejoin.AnyTx.OwnerOne (Fields)
open Lovejoin.AnyTx.OwnerTwo (BoxFields)

structure Proofs where
{''.join(f'  t{i} : ByteString{chr(10)}  z{i} : ByteString{chr(10)}' for i in range(1, n + 1))}
def argsWithProofs (P M {points} key : ByteString) (f : Fields) {box_args} (proofs : List Data) : List Term :=
  [toTerm P, toTerm nftName, toTerm (ownerCtx f.tx
    (.List [{ins_data}])
    (.List [carrierRef f.carrierRef f.carrierAddr (.Map [(.B "", .I 2000000)]) f.carrierScript
      P M 10000000 "" "" 0 800000 testL testL]) f.sigs f.acct proofs)]

def args {params} : List Term :=
  argsWithProofs P M {points} key f {boxes} [{all_proofs}]

def missingArgs {params} : List Term :=
  argsWithProofs P M {points} key f {boxes} [{missing_proofs}]

#prep_uplc owner{n}Tx mixLogicTemplate args {fuel}
#prep_uplc owner{n}Missing mixLogicTemplate missingArgs {fuel}

'''
    for i in range(1, n + 1):
        src += f'''/-- Box {i}'s own proof is required. -/
theorem box{i}_needs_proof {params} :
{pts}    ownProof M f.tx.outputs [{box_refs}] a{i} b{i} p.t{i} p.z{i} = false →
    isUnsuccessful (owner{n}Tx.prop {call}) := by blaster (timeout: 540)

'''
    src += f'''/-- All well-formed boxes and valid proofs pass in this layout. -/
theorem valid_proofs_pass {params} :
    P ≠ "" →
{pts}{proofs}    returnsUnit (owner{n}Tx.prop {call}) := by blaster (timeout: 540)

/-- {n} well-formed boxes cannot leave with only {n-1} proofs. -/
theorem missing_proof_fails {params} :
{pts}    isUnsuccessful (owner{n}Missing.prop {call}) := by blaster (timeout: 540)

end Lovejoin.AnyTx.Owner{n}
'''
    (root / 'Lovejoin' / 'AnyTx' / f'Owner{n}.lean').write_text(src)
