#!/usr/bin/env python3
"""Generate exact-output-value checks for three- and four-box Mix layouts."""
from pathlib import Path
root = Path(__file__).resolve().parent
for kind in ('Ada', 'Token'):
    token = kind == 'Token'
    for n in (3, 4):
        family = f'Mix{kind}{n}'
        source = f'Tok{n}' if token else f'Any{n}'
        ins = ' '.join(f'a{i} b{i}' for i in range(1,n+1))
        outs = ' '.join(f'oa{i} ob{i}' for i in range(1,n+1))
        boxes = ' '.join(f'bx{i}' for i in range(2,n+1))
        boxargs = ' '.join(f'(bx{i} : BoxFields)' for i in range(2,n+1))
        tokenargs = '(tp tn : ByteString) (tq : Integer) ' if token else ''
        tokenvals = 'tp tn tq ' if token else ''
        common = f'(P M : ByteString) (bl : Integer) {tokenargs}({ins} {outs} key : ByteString) (f : Fields) {boxargs} (o : Tail) (p : Proofs)'
        call = f'P M bl {tokenvals}{ins} {outs} key f {boxes} o p'
        conditions = ['first', '!first && second', '!first && !second'] if n == 3 else [
            'first && second', 'first && !second', '!first && second', '!first && !second']
        prefix = ',\n    '.join(f'(if {conditions[i-1]} then badOut M bad oa{i} ob{i} else boxOut M bl {tokenvals}oa{i} ob{i})' for i in range(1,n+1))
        name = f'anyTx{family}BadValue'
        valueargs = f'bl {tokenvals}'.rstrip()
        src=f'''import Lovejoin.AnyTx.{family}
import Blaster

/-! Every prefix box of the {n}-box {kind} layout must have exactly the pool value.
Two Booleans select the output. Generated by `gen-lovejoin-anytx-mix-outputs.py`. -/
namespace Lovejoin.AnyTx.{family}Output
open PlutusCore.ByteString (ByteString)
open PlutusCore.Integer (Integer)
open PlutusCore.Data (Data)
open PlutusCore.UPLC.Term (Term)
open PlutusCore.UPLC.Utils
open Lovejoin.AnyTx.OwnerOne (Fields)
open Lovejoin.AnyTx.OwnerTwo (BoxFields)
open Lovejoin.AnyTx.MixTwo (Tail)
open Lovejoin.AnyTx.{family} (Proofs boxOut argsWithOutputs)
open Lovejoin.V2.{source} (boxValuePool)

def badOut (M : ByteString) (value : Data) (a b : ByteString) : Data :=
  .Constr 0 [.Constr 0 [.Constr 1 [.B M], .Constr 1 []], value,
    .Constr 2 [.Constr 0 [.B a, .B b]], .Constr 1 []]

def args {common} (bad : Data) (first second : Bool) : List Term :=
  argsWithOutputs {call} [
    {prefix}]

#prep_uplc {name} mixLogicTemplate args {65000 if n == 3 else 90000}

theorem wrong_value {common} (bad : Data) (first second : Bool) :
    bad ≠ boxValuePool {valueargs} →
    isUnsuccessful ({name}.prop {call} bad first second) := by blaster (timeout: 540)

end Lovejoin.AnyTx.{family}Output
'''
        (root / 'Lovejoin' / 'AnyTx' / f'{family}Output.lean').write_text(src)
        ns = f'Lovejoin.V2.{source}'
        inputs = ' '.join(f'{ns}.katA{i} {ns}.katB{i}' for i in range(1,n+1))
        outputs = ' '.join(f'{ns}.katOA{i} {ns}.katOB{i}' for i in range(1,n+1))
        pool = f'2000000 {ns}.tokPolicy {ns}.tokName 1000000' if token else '10000000'
        others = ' '.join(f'bx{i}' for i in range(2,n+1))
        invocation = f'{name}.exec nftPolicy mixBoxHash {pool} {inputs} {outputs} userKey f {others} tail proof (.Map [])'
        selections = [('true','false'), ('false','true'), ('false','false')] if n == 3 else [
            ('true','true'), ('true','false'), ('false','true'), ('false','false')]
        guards = '\n'.join(f'#guard endsInError ({invocation} {a} {b})' for a,b in selections)
        imports = ' '.join(['f', 'proof'] + [f'bx{i}' for i in range(2,n+1)])
        controls=f'''import Lovejoin.AnyTx.{family}Output
import Lovejoin.AnyTx.{family}Controls

/-! Changed output value at each prefix position, with the known-good Mix vector.
Generated by `gen-lovejoin-anytx-mix-outputs.py`. -/
namespace Lovejoin.AnyTx.{family}OutputControls
open Seedelf.V1 (endsInError)
open Lovejoin.AnyTx.MixTwoControls (tail)
open Lovejoin.AnyTx.{family}Controls ({imports})
open Lovejoin.V2 (nftPolicy mixBoxHash userKey)

{guards}

end Lovejoin.AnyTx.{family}OutputControls
'''
        (root / 'Lovejoin' / 'AnyTx' / f'{family}OutputControls.lean').write_text(controls)
