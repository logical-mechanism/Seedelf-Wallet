#!/usr/bin/env python3
"""Generate full-validator recovery proofs for non-box inline datum shapes."""
from pathlib import Path
root = Path(__file__).resolve().parent
kinds = [
    ('bytes', '(x : ByteString)', '.B x', ''),
    ('integer', '(x : Integer)', '.I x', ''),
    ('list', '(xs : List Data)', '.List xs', ''),
    ('map', '(xs : List (Data × Data))', '.Map xs', ''),
    ('wrong_tag', '(tag : Integer) (xs : List Data) (hTag : tag ≠ 0)', '.Constr tag xs', 'tag'),
    ('no_fields', '', '.Constr 0 []', ''),
    ('one_field', '(x : Data)', '.Constr 0 [x]', ''),
    ('three_or_more_fields', '(x y z : Data) (xs : List Data)', '.Constr 0 (x :: y :: z :: xs)', ''),
]
for position in ('first', 'second'):
    for name, param, v in [('integer', '(x : Integer)', '.I x'), ('list', '(xs : List Data)', '.List xs'),
                            ('map', '(xs : List (Data × Data))', '.Map xs'), ('constr', '(tag : Integer) (xs : List Data)', '.Constr tag xs')]:
        fields = f'{v}, y' if position == 'first' else f'.B a, {v}'
        extra = '(y : Data)' if position == 'first' else '(a : ByteString)'
        kinds.append((f'{position}_{name}', f'{param} {extra}', f'.Constr 0 [{fields}]', ''))

head='''import Lovejoin.AnyTx.BoxAll

/-! Whole-validator recovery for non-box inline datum shapes and arbitrary-length
input prefixes/suffixes. Generated by `gen-lovejoin-box-shapes.py`. -/
namespace Lovejoin.AnyTx.BoxMalformedShapes
open CardanoLedgerApi.IsData.Class (toTerm)
open PlutusCore.ByteString (ByteString)
open PlutusCore.Integer (Integer)
open PlutusCore.Data (Data)
open PlutusCore.UPLC.CekValue (CekValue Environment)
open PlutusCore.UPLC.CekMachine
open Seedelf.V1 (TxRest)
open Seedelf.V1.LinesAll
open Lovejoin.AnyTx
open Lovejoin.AnyTx.CekCase
open Lovejoin.AnyTx.BoxSearch
set_option maxHeartbeats 0

'''
for name,param,datum,kind in kinds:
    body=f'''/-- The inline datum shape `{name}` takes the recovery path. -/
theorem {name}_recovers (L : ByteString) (r : TxRest) (sigs red ref rd wdrl addr value script : Data)
    (before after : List (Data × Data)) (hBefore : ∀ pair ∈ before, pair.1 ≠ ref) {param} :
    ∃ n, cekExecuteProgram mixBoxTemplate.script
      [toTerm L, toTerm (boxSpendCtx r
        (.List (inputList (before ++ (ref, .Constr 0 [addr, value, .Constr 2 [{datum}], script]) :: after)))
        wdrl sigs red ref rd)] n = .Halt (.VCon .Unit) := by
  let out : Data := .Constr 0 [addr, value, .Constr 2 [{datum}], script]
  have hInput : ∀ (c0 c1 c2 c10 c11 c12 c13 c14 c15 c16 : CekValue) (rest : Environment),
      Ev default searchBody
        (.VCon (.ConstDataList (inputList (before ++ (ref, out) :: after))) ::
          .VLam searchLoop (searchEnv ref c0 c1 c2 c10 c11 c12 c13 c14 c15 c16 rest) ::
          searchEnv ref c0 c1 c2 c10 c11 c12 c13 c14 c15 c16 rest)
        (some (.VCon (.Data (.Constr 0 [inputData ref out])))) := by
    intro c0 c1 c2 c10 c11 c12 c13 c14 c15 c16 rest
    exact search_matched ref out before after hBefore c0 c1 c2 c10 c11 c12 c13 c14 c15 c16 rest
  dsimp only [out] at hInput
'''
    if kind=='tag':
        body+='''  have he : PlutusCore.Integer.equalsInteger 0 tag = false := by
    simp [PlutusCore.Integer.equalsInteger, Ne.symm hTag]
'''
    body+='''  apply exec_halt_of_ev
  cek_v3_using [hInput]
'''
    if kind=='tag': body+='''  all_goals try rw [he]
  cek_v3_using [hInput]
'''
    head+=body+'\n'
head+='end Lovejoin.AnyTx.BoxMalformedShapes\n'
(root/'Lovejoin/AnyTx/BoxMalformedShapes.lean').write_text(head)
