#!/usr/bin/env python3
"""Generate bounded arbitrary-context Mix proofs for three and four boxes."""
from pathlib import Path
root = Path(__file__).resolve().parent
for kind in ('Ada', 'Token'):
    token = kind == 'Token'
    for n in (3, 4):
        family = f'Mix{kind}{n}'
        source = f'Tok{n}' if token else f'Any{n}'
        spec = f'MixTok{n}Spec' if token else f'MixAny{n}Spec'
        ins = ' '.join(f'a{i} b{i}' for i in range(1, n + 1))
        outs = ' '.join(f'oa{i} ob{i}' for i in range(1, n + 1))
        boxes = ' '.join(f'bx{i}' for i in range(2, n + 1))
        boxargs = ' '.join(f'(bx{i} : BoxFields)' for i in range(2, n + 1))
        tokenargs = '(tp tn : ByteString) (tq : Integer) ' if token else ''
        tokenvals = 'tp tn tq ' if token else ''
        fields = [(k, i, j) for i in range(1, n+1) for j in range(1, n+1) for k in ('t0', 't1', 'c', 'z')]
        def pf(k, i, j): return f'{k}{i}{j}'
        allfields = ' '.join('p.'+pf(k,i,j) for k,i,j in fields)
        pts = ''.join(f'    wellFormed {prefix}a{i} {prefix}b{i} = true →\n' for prefix in ('', 'o') for i in range(1,n+1))
        in_list = ['boxIn f.boxRef M f.boxStake f.boxValue f.boxScript a1 b1'] + [
            f'boxIn bx{i}.ref M bx{i}.stake bx{i}.value bx{i}.script a{i} b{i}' for i in range(2,n+1)] + [
            'otherIn f.keyRef 0 key f.keyStake f.keyValue f.keyDatum f.keyScript']
        out_list = [f'boxOut M bl {tokenvals}oa{i} ob{i}' for i in range(1,n+1)] + ['keyOut o']
        joined_ins = ',\n      '.join(in_list)
        joined_outs = ', '.join(out_list[:-1])
        carrier_token = 'tp tn tq' if token else '"" "" 0'
        baseparams = f'(P M : ByteString) (bl : Integer) {tokenargs}({ins} {outs} key : ByteString) (f : Fields) {boxargs} (o : Tail) (p : Proofs)'
        call = f'P M bl {tokenvals}{ins} {outs} key f {boxes} o p'
        name = f'anyTx{family}'
        fuel = 50000 if n == 3 else 75000
        boxout = '''def boxOut (M : ByteString) (bl : Integer) (tp tn : ByteString) (tq : Integer) (a b : ByteString) : Data :=
  .Constr 0 [.Constr 0 [.Constr 1 [.B M], .Constr 1 []],
    .Map [(.B "", .Map [(.B "", .I bl)]), (.B tp, .Map [(.B tn, .I tq)])],
    .Constr 2 [.Constr 0 [.B a, .B b]], .Constr 1 []]
''' if token else '''def boxOut (M : ByteString) (bl : Integer) (a b : ByteString) : Data :=
  .Constr 0 [.Constr 0 [.Constr 1 [.B M], .Constr 1 []],
    .Map [(.B "", .Map [(.B "", .I bl)])], .Constr 2 [.Constr 0 [.B a, .B b]], .Constr 1 []]
'''
        src=f'''import Lovejoin.AnyTx.OwnerTwo
import Lovejoin.AnyTx.MixTwo
import Lovejoin.V2.{spec}
import Blaster

/-! {n}-box {kind} Mix, plus a key input and output. Input references, values, unused
input/output fields and unrelated transaction fields are arbitrary. There is one
reference carrier; the output boxes have the indicated pool value. Generated by
`gen-lovejoin-anytx-mixes.py`. -/
namespace Lovejoin.AnyTx.{family}
open CardanoLedgerApi.IsData.Class (toTerm)
open PlutusCore.ByteString (ByteString)
open PlutusCore.Integer (Integer)
open PlutusCore.Data (Data)
open PlutusCore.UPLC.Term (Term)
open PlutusCore.UPLC.Utils
open Seedelf.V1 (returnsUnit)
open Lovejoin.Classic (wellFormed)
open Lovejoin.Template (nftName)
open Lovejoin.AnyTx
open Lovejoin.AnyTx.OwnerOne (Fields)
open Lovejoin.AnyTx.OwnerTwo (BoxFields)
open Lovejoin.AnyTx.MixTwo (Tail keyOut)
open Lovejoin.V2 (branchHolds)
open Lovejoin.V2.{source} (proofsRedeemerPool challengeHoldsPool mixAcceptsPool)

structure Proofs where
{''.join('  '+pf(k,i,j)+' : ByteString'+chr(10) for k,i,j in fields)}
{boxout}
def argsWithOutputs {baseparams} (boxOutputs : List Data) : List Term :=
  let tx := {{ f.tx with outputs := .List (boxOutputs ++ [keyOut o]) }}
  let inputs := .List [{joined_ins}]
  let refs := .List [carrierRef f.carrierRef f.carrierAddr (.Map [(.B "", .I 2000000)]) f.carrierScript
    P M bl {carrier_token} 800000 testL testL]
  let red := proofsRedeemerPool {allfields}
  [toTerm P, toTerm nftName, toTerm (Data.Constr 0 [withInputs tx inputs refs f.sigs, red, .Constr 2 [f.acct]])]

def args {baseparams} : List Term :=
  argsWithOutputs {call} [{joined_outs}]

#prep_uplc {name} mixLogicTemplate args {fuel}

'''
        for i in range(1,n+1):
            ci=' '.join(f'p.t0{i}{j} p.t1{i}{j} p.c{i}{j}' for j in range(1,n+1))
            src+=f'''theorem box{i}_challenge {baseparams} :
    challengeHoldsPool M bl {tokenvals}{outs} a{i} b{i} {ci} = false →
    isUnsuccessful ({name}.prop {call}) := by blaster (timeout: 540)

'''
            for j in range(1,n+1):
                src+=f'''theorem box{i}_branch{j} {baseparams} :
    branchHolds a{i} b{i} oa{j} ob{j} p.t0{i}{j} p.t1{i}{j} p.c{i}{j} p.z{i}{j} = false →
    isUnsuccessful ({name}.prop {call}) := by blaster (timeout: 540)

'''
        tokprem = 'tp ≠ "" → tq ≠ 0 → ' if token else ''
        src+=f'''theorem valid_proofs_pass {baseparams} :
    P ≠ "" → bl ≠ 0 → {tokprem}
{pts}    mixAcceptsPool M bl {tokenvals}{ins} {outs} {allfields} = true →
    returnsUnit ({name}.prop {call}) := by blaster (timeout: 540)

end Lovejoin.AnyTx.{family}
'''
        (root / 'Lovejoin' / 'AnyTx' / f'{family}.lean').write_text(src)

# The controls reuse Lovejoin's independent known-answer vectors and run each new
# context with the valid proof, then with the first and last response changed.
for kind in ('Ada', 'Token'):
    token = kind == 'Token'
    for n in (3, 4):
        family = f'Mix{kind}{n}'
        source = f'Tok{n}' if token else f'Any{n}'
        namespace = f'Lovejoin.V2.{source}'
        proofvalues = []
        for i in range(1, n+1):
            for j in range(1, n+1):
                proofvalues.extend(f'{namespace}.{prefix}{i}{j}' for prefix in ('katT0', 'katT1', 'katC', 'katZ'))
        proofdata = ', '.join(proofvalues)
        inputs = ' '.join(f'{namespace}.katA{i} {namespace}.katB{i}' for i in range(1,n+1))
        outputs = ' '.join(f'{namespace}.katOA{i} {namespace}.katOB{i}' for i in range(1,n+1))
        tokenargs = f'2000000 {namespace}.tokPolicy {namespace}.tokName 1000000' if token else '10000000'
        value = f'{namespace}.boxValuePool 2000000 {namespace}.tokPolicy {namespace}.tokName 1000000' if token else 'adaValue 10000000'
        boxdefs = '\n'.join(
            f'def bx{i} : BoxFields := {{ box2 with ref := refAt {i+1}, value := inputValue }}' for i in range(3,n+1))
        extra = ' '.join(f'bx{i}' for i in range(3,n+1))
        call = f'anyTx{family}.exec nftPolicy mixBoxHash {tokenargs} {inputs} {outputs} userKey f bx2 {extra} tail'
        src=f'''import Lovejoin.AnyTx.{family}
import Lovejoin.AnyTx.MixTwoControls

/-! Passing and modified independent Mix vectors in the expanded {n}-box {kind} layout.
Generated by `gen-lovejoin-anytx-mixes.py`. -/
namespace Lovejoin.AnyTx.{family}Controls
open Seedelf.V1 (endsWithUnit endsInError)
open Lovejoin.AnyTx (adaValue refAt)
open Lovejoin.AnyTx.OwnerTwo (BoxFields)
open Lovejoin.AnyTx.OwnerMoreControls (fields box2)
open Lovejoin.AnyTx.MixTwoControls (tail)
open Lovejoin.V2 (nftPolicy mixBoxHash userKey)

private def inputValue := {value}
def f := {{ fields 1000000 with boxValue := inputValue, keyValue := adaValue 5200000 }}
def bx2 : BoxFields := {{ box2 with value := inputValue }}
{boxdefs}
def proof : Lovejoin.AnyTx.{family}.Proofs := ⟨{proofdata}⟩

#guard endsWithUnit ({call} proof)
#guard endsInError ({call} {{ proof with z11 := "" }})
#guard endsInError ({call} {{ proof with z{n}{n} := "" }})

end Lovejoin.AnyTx.{family}Controls
'''
        (root / 'Lovejoin' / 'AnyTx' / f'{family}Controls.lean').write_text(src)
